            "read-page" -> listOf("Step 1: Open a physical book", "Step 2: Read one page slowly")
            "read-poem" -> listOf("Step 1: Find a short poem", "Step 2: Read it twice")
            "read-highlight" -> listOf("Step 1: Pencil ready", "Step 2: Mark three key lines")
            "read-aloud" -> listOf("Step 1: Pick a paragraph", "Step 2: Read it out loud")
            "read-margin" -> listOf("Step 1: Find a strong sentence", "Step 2: Write one margin note")
            "gym-mobility" -> listOf("Step 1: Phone face-down", "Step 2: Hips, calves, squat hold")
            "walk-5" -> listOf("Step 1: Step outside", "Step 2: Notice three real details")
            "fitness-plank" -> listOf("Step 1: Elbows under shoulders", "Step 2: Hold clean form")
            "fitness-squats" -> listOf("Step 1: Feet shoulder-width", "Step 2: 20 slow squats")
