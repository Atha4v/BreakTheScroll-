        val specific = when (id) {
            "code-stretch" -> listOf("Step 1: Stand up from the chair", "Step 2: Roll shoulders back")
            "code-git-repo" -> listOf("Step 1: Open terminal in a folder", "Step 2: git init + first commit")
            "code-kata" -> listOf("Step 1: Open one easy problem", "Step 2: Solve a single test case")
            "code-refactor" -> listOf("Step 1: Find one muddy name", "Step 2: Rename it cleanly")
