    private fun item(
        id: String,
        title: String,
        description: String,
        minutes: Int,
        category: String,
        tag: String,
        illustration: String,
        image: String,
        personalized: Boolean,
        start: Int,
        end: Int,
        durationSeconds: Int,
    ) = ActivityCatalogEntity(
        id = id,
        title = title,
        description = description,
        durationMinutes = minutes,
        category = category,
        difficulty = when {
            durationSeconds >= 300 -> 3
            durationSeconds >= 120 -> 2
            else -> 1
        },
        illustration = illustration,
        interestTag = tag,
        imageUrl = image,
        isPersonalized = personalized,
        heroColorStart = start,
        heroColorEnd = end,
        durationSeconds = durationSeconds.coerceAtLeast(15),
    )
